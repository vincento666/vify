def _case(
    case_id: str,
    category: str,
    message: str,
    task_key: str,
    business_key: str | None = None,
    *,
    events: list[str],
    recommendation: str,
    reply: str,
    action_states: list[str] | None = None,
    timeout_count: int = 0,
    failure_count: int = 0,
) -> CustomerAssistantEvalCase:
    return CustomerAssistantEvalCase(
        id=case_id,
        category=category,
        message=message,
        task_recognition=TaskRecognitionEval(
            expected_task_key=task_key,
            expected_business_key=business_key,
            actual_task_key=task_key,
            actual_business_key=business_key,
        ),
        recommendation=RecommendationEval(
            operator_recommendation=recommendation,
            customer_reply=reply,
        ),
        safety=SafetyEval(
            unsafe_proposed_action_leak=False,
            high_risk_action_executed_without_confirmation=False,
        ),
        timing=TimingEval(timeout_count=timeout_count, failure_count=failure_count),
        source="golden",
        metadata={
            "expected_task_keys": [task_key],
            "expected_action_states": action_states or [],
            "expected_event_types": events,
            "synthetic": True,
        },
    )
